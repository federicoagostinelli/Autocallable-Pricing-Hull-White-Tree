function pricedProduct = prepareProductForPricing(product, market)
%PREPAREPRODUCTFORPRICING Add market-dependent pricing inputs.
%
%   pricedProduct = PREPAREPRODUCTFORPRICING(product, market)
%
%   enriches the contractual product struct with market-dependent quantities
%   required to price the Assignment 6 certificate / hedging swap.
%
%   Party A:
%       Euribor 3M + spread, quarterly, ACT/360, Modified Following.
%
%   Party B:
%       Annual equity-linked coupons, 30/360, payment dates subject to
%       Following Business Day Convention, reset dates 2 TARGET business
%       days before the corresponding payment dates.
%
%   This function does not compute coupon payoffs and does not apply the
%   early redemption / cancellation rule. It only prepares dates, times,
%   accrual factors, discount factors, forward rates and underlying inputs.
%
%   Required helper functions:
%
%       ensureDatetime
%       businessDateOffsetTarget
%       addTargetBusinessDays
%       getDiscountFactorByZeroRatesLinearInterp

    pricedProduct = product;

    %% Defensive date conversion

    pricedProduct.startDate = ensureDatetime(pricedProduct.startDate);
    pricedProduct.endDate = ensureDatetime(pricedProduct.endDate);

    %% Party A: quarterly Euribor 3M floating leg

    partyA = pricedProduct.partyA;

    numberOfPartyAPeriods = ...
        pricedProduct.maturityYears * partyA.paymentsPerYear;

    partyAIdx = 1:numberOfPartyAPeriods;

    partyA.periodStartDates = market.tenor.dates(partyAIdx).';
    partyA.paymentDates = market.tenor.dates(partyAIdx + 1).';

    partyA.resetTimes = market.tenor.resetTimes(partyAIdx).';
    partyA.paymentTimes = market.tenor.times(partyAIdx + 1).';
    partyA.delta = market.tenor.delta(partyAIdx).';

    partyA.periodStartDiscounts = getDiscountFactorByZeroRatesLinearInterp( ...
        market.dateInfo.refDate, ...
        partyA.periodStartDates, ...
        market.dates, ...
        market.discounts);

    partyA.paymentDiscounts = getDiscountFactorByZeroRatesLinearInterp( ...
        market.dateInfo.refDate, ...
        partyA.paymentDates, ...
        market.dates, ...
        market.discounts);

    partyA.periodStartDiscounts = partyA.periodStartDiscounts(:);
    partyA.paymentDiscounts = partyA.paymentDiscounts(:);

    partyA.forwardRates = ...
        (partyA.periodStartDiscounts ./ partyA.paymentDiscounts - 1.0) ...
        ./ partyA.delta;

    pricedProduct.partyA = partyA;

    %% Party B: annual equity-linked coupon leg

    partyB = pricedProduct.partyB;

    numberOfPartyBCoupons = ...
        pricedProduct.maturityYears * partyB.paymentsPerYear;

    couponIdx = 1:numberOfPartyBCoupons;

    partyB.periodStartDates = arrayfun( ...
        @(iCoupon) businessDateOffsetTarget( ...
            pricedProduct.startDate, ...
            iCoupon - 1, ...
            0, ...
            0, ...
            partyB.accrualAdjust), ...
        couponIdx).';

    partyB.paymentDates = arrayfun( ...
        @(iCoupon) businessDateOffsetTarget( ...
            pricedProduct.startDate, ...
            iCoupon, ...
            0, ...
            0, ...
            partyB.paymentAdjust), ...
        couponIdx).';

    partyB.resetDates = addTargetBusinessDays( ...
        partyB.paymentDates, ...
        -partyB.resetLagBusinessDays);

    partyB.resetTimes = yearfrac( ...
        market.dateInfo.refDate, ...
        partyB.resetDates, ...
        pricedProduct.blackDayCount);

    partyB.paymentTimes = yearfrac( ...
        market.dateInfo.refDate, ...
        partyB.paymentDates, ...
        pricedProduct.blackDayCount);

    partyB.delta = yearfrac( ...
        partyB.periodStartDates, ...
        partyB.paymentDates, ...
        partyB.dayCount);

    partyB.paymentDiscounts = getDiscountFactorByZeroRatesLinearInterp( ...
        market.dateInfo.refDate, ...
        partyB.paymentDates, ...
        market.dates, ...
        market.discounts);

    partyB.resetDiscounts = getDiscountFactorByZeroRatesLinearInterp( ...
        market.dateInfo.refDate, ...
        partyB.resetDates, ...
        market.dates, ...
        market.discounts);

    partyB.resetTimes = partyB.resetTimes(:);
    partyB.paymentTimes = partyB.paymentTimes(:);
    partyB.delta = partyB.delta(:);
    partyB.paymentDiscounts = partyB.paymentDiscounts(:);
    partyB.resetDiscounts = partyB.resetDiscounts(:);

    pricedProduct.partyB = partyB;

    %% Underlying market inputs

    pricedProduct.underlying.spot = market.equity.spot;
    pricedProduct.underlying.dividendYield = market.equity.dividendYield;
    pricedProduct.underlying.strikes = market.equity.strikes;
    pricedProduct.underlying.volSmile = market.equity.volSmile;

end